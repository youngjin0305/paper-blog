    expect(page.locator('#atlas-detail')).to_contain_text('계산을 이용하는 공격 관점')
    search.fill('truncated differential cryptoanalysis')
    expect(page.locator('.field-search-results')).to_contain_text('절단 차분 분석')
    search.fill('Truncated and higher order differentials')
    expect(page.locator('.field-search-results')).to_contain_text('차분 분석 → 절단 차분 분석')
